#!/usr/bin/env bash
# bufcap.sh - build, load and unload the fixed RLC DL buffer-cap codelet (Demo 3).
#
#   bash buffer-control-experiments/bufcap.sh build [SIZE ...]   # default: off 16k 64k 256k 1m
#   bash buffer-control-experiments/bufcap.sh load SIZE          # e.g. 256k; swaps out any loaded cap
#   bash buffer-control-experiments/bufcap.sh off                # restore the configured buffer, unload
#   bash buffer-control-experiments/bufcap.sh unload             # unload only: the last cap STAYS in force
#   bash buffer-control-experiments/bufcap.sh status
#   bash buffer-control-experiments/bufcap.sh list               # sizes already built
#
# SIZE is bytes with an optional k (x1024) or m (x1048576) suffix: 16k, 200000, 1m.
# Every cap is its own object (bufcap_<SIZE>.o) built from codelets/bufcap/bufcap.cpp,
# and every one uses codeletset_id "bufcap", so only one can be loaded at a time.
#
# Why "off" exists: the gNB keeps the last limit after a control codelet is unloaded.
# "off" loads bufcap_off (which writes the CONFIGURED limits back) until the next DL
# packet has passed, then unloads it. It needs downlink traffic to take effect.
set -uo pipefail
export PATH="$HOME/.local/bin:$PATH"
export KUBECONFIG="${KUBECONFIG:-$(k3d kubeconfig write "${K3D_CLUSTER:-janus-cluster}" 2>/dev/null)}"
HR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CDIR=$HR/jrtc-apps/codelets/bufcap          # jrtc-0 sees this as /codelets/bufcap
ADIR=$HR/jrtc-apps/jrtc_apps/bufcap         # jrtc-0 sees this as /apps/bufcap
STATE=$HR/buffer-control-experiments/.bufcap_state
NS=ran; POD=srs-gnb-du1-0
SDK=ghcr.io/microsoft/jrtc-apps/srs-jbpf-sdk:latest

gnb() { timeout "${2:-30}" kubectl exec -n $NS $POD -c ocudujbpf -- bash -c "$1" 2>/dev/null; }
jctl() {  # jctl load|unload SIZE
  timeout 150 kubectl exec -n $NS jrtc-0 -c jrtc -- bash -c \
    "export JRTC_APPS=/apps JBPF_CODELETS=/codelets; /jrtc/out/bin/jrtc-ctl $1 -c /apps/bufcap/deployment_$2.yaml --log-level error 2>&1 | grep -iE 'error|fail' | tail -2"
}
bytes() {  # 16k -> 16384, 1m -> 1048576, off -> 0
  case "$1" in
    off) echo 0 ;;
    *[kK]) echo $(( ${1%[kK]} * 1024 )) ;;
    *[mM]) echo $(( ${1%[mM]} * 1048576 )) ;;
    *[!0-9]*|'') echo "bad size '$1' (use e.g. 16k, 200000, 1m, off)" >&2; return 1 ;;
    *) echo "$1" ;;
  esac
}
LOGS="/tmp/gnb.stdout /tmp/gnb.log"   # the jbpf agent logs to the gNB's stdout: gnb.stdout under setup_zmq_chan_demo.sh, gnb.log in older setups
counts() {  # "<loads> <removes>" of any codelet named bufcap / rlc_ctrl since this gNB started
  gnb "echo \$(cat $LOGS 2>/dev/null | grep -aoE 'loaded successfully: [a-z_0-9]+' | grep -cx 'loaded successfully: $1') \$(cat $LOGS 2>/dev/null | grep -ac 'Codelet $1 removed successfully')"
}
attached() { set -- $(counts "$1"); [ "${1:-0}" -gt "${2:-0}" ]; }
cfg_kb() {  # the RLC DL queue the gNB is configured with, in kB: queue-bytes in its -c files, else OCUDU's default
  local b
  b=$(gnb 'p=$(pgrep -xo gnb) && cd /proc/$p/cwd && tr "\0" "\n" < /proc/$p/cmdline | sed -n "/^-c$/{n;p}" | xargs -r cat 2>/dev/null | grep -oE "queue-bytes:[[:space:]]*[0-9]+" | grep -oE "[0-9]+$" | head -1')
  echo $(( ${b:-6172672} / 1024 ))
}
current() { cat "$STATE" 2>/dev/null || echo none; }

mark() {  # mark LIMIT_KB TEXT: cap-in-force metric + Grafana annotation + local event log
  local now_ns; now_ns=$(date +%s%N)
  [ -n "$1" ] && curl -s -m 5 -XPOST http://localhost:30491/write --data-binary "bufcap limit_kb=$1 $now_ns" >/dev/null
  curl -s -m 5 -u admin:admin -H 'Content-Type: application/json' -XPOST http://localhost:30490/api/annotations \
    -d "{\"time\":$(( now_ns / 1000000 )),\"tags\":[\"bufcap\"],\"text\":\"$2\"}" >/dev/null
  echo "{\"t\": $(( now_ns / 1000000 ))e-3, \"limit_kb\": ${1:-null}, \"text\": \"$2\"}" >> "$HR/buffer-control-experiments/.bufcap_events.jsonl"
}

build_one() {
  local n=$1 b
  b=$(bytes "$n") || return 1
  mkdir -p "$ADIR"
  docker run --rm --user "$(id -u):$(id -g)" -v "$HR/jrtc-apps/codelets:/codelet" \
    --entrypoint /usr/bin/make "$SDK" -C /codelet/bufcap one NAME="$n" CAP="$b" 2>&1 \
    | grep -E "^---|rror|verifier" | sed 's/^/  /'
  [ -f "$CDIR/bufcap_$n.o" ] || { echo "  !! build failed for $n"; return 1; }
  cat > "$CDIR/bufcap_$n.yaml" <<EOF
# generated by buffer-control-experiments/bufcap.sh -- fixed RLC DL buffer cap ($n = $b bytes; 0 = restore config)
codeletset_id: bufcap
codelet_descriptor:
  - codelet_name: bufcap
    codelet_path: \${JBPF_CODELETS}/bufcap/bufcap_$n.o
    hook_name: rlc_dl_ctrl
    priority: 1
EOF
  cat > "$ADIR/deployment_$n.yaml" <<EOF
# generated by buffer-control-experiments/bufcap.sh
name: bufcap
jbpf:
  device:
    - id: 1
      host: srs-gnb-du1-proxy.ran.svc.cluster.local
      port: 30450
  codelet_set:
    - device: 1
      config: \${JBPF_CODELETS}/bufcap/bufcap_$n.yaml
EOF
  echo "  built bufcap_$n ($b bytes)"
}

stage() {  # the gNB agent loads the .o from ITS OWN /codelets, not jrtc-0's; always re-copy (rebuilds)
  gnb "mkdir -p /codelets/bufcap"
  kubectl cp "$CDIR/bufcap_$1.o" "$NS/$POD:/codelets/bufcap/bufcap_$1.o" -c ocudujbpf >/dev/null 2>&1
}

do_unload() {
  attached bufcap || { echo "  no bufcap attached"; rm -f "$STATE"; return 0; }
  jctl unload off
  attached bufcap && { echo "  !! unload failed"; return 1; }
  echo "  unloaded bufcap_$(current)"
  rm -f "$STATE"
}

do_load() {
  local n=$1
  [ -f "$CDIR/bufcap_$n.o" ] || build_one "$n" || return 1
  if attached rlc_ctrl; then
    echo "  !! bufctl (rlc_ctrl) is attached to rlc_dl_ctrl; quit bufctl_cli.py first"; return 1
  fi
  attached bufcap && { do_unload || return 1; }
  stage "$n" || { echo "  !! could not copy bufcap_$n.o into the gNB container"; return 1; }
  set -- $(counts bufcap); local before=${1:-0}
  jctl load "$n"
  set -- $(counts bufcap)
  [ "${1:-0}" -gt "$before" ] || { echo "  !! load of bufcap_$n failed (see $LOGS in the gNB container)"; return 1; }
  echo "$n" > "$STATE"
  if [ "$n" != off ]; then mark $(( $(bytes "$n") / 1024 )) "cap $n"; fi
  echo "  loaded bufcap_$n"
}

CMD="${1:-status}"; shift 2>/dev/null || true
case "$CMD" in
  build)
    [ $# -eq 0 ] && set -- off 16k 64k 256k 1m
    for n in "$@"; do build_one "$n"; done ;;
  load)
    [ $# -eq 1 ] || { echo "usage: bufcap.sh load SIZE"; exit 2; }
    do_load "$1" ;;
  unload)
    if attached bufcap; then
      cur=$(current); do_unload && mark "" "unloaded bufcap_$cur (cap stays in force)"
      echo "  note: the last cap stays in force in the gNB. 'bufcap.sh off' restores the configured size."
    else
      echo "  no bufcap attached"; rm -f "$STATE"
    fi ;;
  off)
    do_load off || exit 1
    sleep "${BUFCAP_OFF_HOLD:-2}"     # the next DL packet applies the configured limits
    do_unload >/dev/null && echo "  configured buffer restored; bufcap unloaded"
    kb=$(cfg_kb); mark "$kb" "no cap (configured $kb kB)" ;;
  status)
    set -- $(counts bufcap)
    echo "  bufcap: loads=${1:-0} removes=${2:-0} -> $(attached bufcap && echo "ATTACHED ($(current))" || echo "not attached")"
    set -- $(counts rlc_ctrl)
    echo "  bufctl: loads=${1:-0} removes=${2:-0}" ;;
  list)
    ls "$CDIR"/bufcap_*.o 2>/dev/null | sed 's#.*/bufcap_##; s#\.o$##' | tr '\n' ' '; echo ;;
  *) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
