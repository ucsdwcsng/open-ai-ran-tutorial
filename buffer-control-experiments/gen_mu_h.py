#!/usr/bin/env python3
"""mu_table.csv (mcs,se,mbps) -> C header with mu_Bps(mcs) (bytes/s) as a branch tree.
Usage: gen_mu_h.py mu_table.csv OUT.h"""
import csv
import sys

mu = [int(float(r["mbps"]) * 1e6 / 8) for r in csv.DictReader(open(sys.argv[1]))]


def tree(lo, hi, ind):
    if hi - lo == 1:
        return f"{ind}return {mu[lo]};\n"
    mid = (lo + hi) // 2
    return f"{ind}if (m < {mid}) {{\n" + tree(lo, mid, ind + "    ") + f"{ind}}}\n" + tree(mid, hi, ind)


with open(sys.argv[2], "w") as f:
    f.write(f"// generated by gen_mu_h.py from {sys.argv[1]} -- DL rate (bytes/s) per MCS 0..{len(mu) - 1}\n")
    f.write("static inline uint32_t mu_Bps(uint32_t m)\n{\n    if (m > %d) {\n        m = %d;\n    }\n" % (len(mu) - 1, len(mu) - 1))
    f.write(tree(0, len(mu), "    ") + "}\n")
