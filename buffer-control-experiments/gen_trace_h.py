#!/usr/bin/env python3
"""traces/<name>.csv (second,cqi,mcs) -> a C header with trace_mcs(second) as a branch tree
(no lookup table, so the eBPF verifier sees only compares). Usage: gen_trace_h.py CSV OUT.h"""
import csv
import sys

rows = list(csv.DictReader(open(sys.argv[1])))
mcs = [min(28, int(r["mcs"])) for r in rows]


def tree(lo, hi, ind):
    if hi - lo == 1:
        return f"{ind}return {mcs[lo]};\n"
    mid = (lo + hi) // 2
    return (f"{ind}if (s < {mid}) {{\n" + tree(lo, mid, ind + "    ") + f"{ind}}}\n" + tree(mid, hi, ind))


with open(sys.argv[2], "w") as f:
    f.write(f"// generated by gen_trace_h.py from {sys.argv[1]} -- do not edit\n")
    f.write(f"#define TRACE_LEN ({len(mcs)})\n")
    f.write("static inline uint32_t trace_mcs(uint32_t s)\n{\n" + tree(0, len(mcs), "    ") + "}\n")
print(f"{sys.argv[2]}: {len(mcs)} s")
